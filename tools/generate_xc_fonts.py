"""Generate small LVGL 9 subsets for the XC remote. Regeneration needs Pillow."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets/fonts"


def inventory():
    # Common words in studio, stage, and home SSIDs shown in the device status.
    network_names = "摄影棚演播厅舞台控制室导播车活动现场客厅办公室家庭路由访客工作间"
    return set(range(32, 127)) | set(map(ord, network_names)) | {
        ord(c)
        for filename in ("xc_main.c", "xc_ui.c")
        for literal in re.findall(r'"([^"\n]*)"', (ROOT / "main" / filename).read_text("utf-8"))
        for c in literal
        if ord(c) > 127
    }


def generate(path, size, codes):
    from PIL import ImageFont

    font = ImageFont.truetype(path, size)
    pixels, glyphs, expected = [], ["    {0},"], []
    baseline = (size + 1) // 4
    for code in sorted(codes):
        ch = chr(code)
        mask, (x, y) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        values = [(value * 15 + 127) // 255 for value in mask]
        expected.append((len(pixels), values))
        glyphs.append(
            f"    {{{len(pixels)}, {round(font.getlength(ch) * 16)}, {w}, {h}, {x}, {-y-h}}},"
        )
        if len(values) % 2:
            values = values + [0]
        pixels.extend(a << 4 | b for a, b in zip(values[::2], values[1::2]))

    sparse = sorted(codes - set(range(32, 127)))
    name = f"xc_font_{size}"
    bitmap = "\n".join(
        "    " + ", ".join(f"0x{p:02x}" for p in pixels[i:i+16]) + ","
        for i in range(0, len(pixels), 16)
    )
    source = f"""/* Generated by tools/generate_xc_fonts.py. SIL OFL 1.1. */
#include "lvgl.h"

static const uint8_t bitmap[] = {{
{bitmap}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {{
{chr(10).join(glyphs)}
}};
static const uint16_t offsets[] = {{
    {", ".join(str(c - sparse[0]) for c in sparse)}
}};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{.range_start = 32, .range_length = 95, .glyph_id_start = 1,
      .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},
    {{.range_start = {sparse[0]}, .range_length = {sparse[-1] - sparse[0] + 1}, .glyph_id_start = 96,
      .unicode_list = offsets, .list_length = {len(sparse)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}},
}};
static const lv_font_fmt_txt_dsc_t description = {{
    .glyph_bitmap = bitmap, .glyph_dsc = glyphs, .cmaps = cmaps, .cmap_num = 2,
    .bpp = 4, .bitmap_format = LV_FONT_FMT_TXT_PLAIN,
}};
const lv_font_t {name} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {size+5}, .base_line = {baseline}, .dsc = &description,
}};
"""
    path_out = OUT / f"{name}.c"
    path_out.write_text(source, encoding="utf-8", newline="\n")
    encoded = path_out.read_text("utf-8").split("bitmap[] = {\n", 1)[1].split("};", 1)[0]
    decoded = [q for v in re.findall(r"0x([0-9a-f]{2})", encoded) for q in (int(v[0], 16), int(v[1], 16))]
    for pos, glyph in expected:
        assert decoded[pos*2:pos*2+len(glyph)] == glyph


def check(codes):
    for size in (14, 20):
        source = (OUT / f"xc_font_{size}.c").read_text("utf-8")
        values = re.search(r"offsets\[\] = \{\s*([\d, ]+)\s*\}", source)[1]
        start = int(re.findall(r"\.range_start = (\d+)", source)[1])
        mapped = set(range(32, 127)) | {start + int(v) for v in values.split(",")}
        assert codes <= mapped, f"Missing {size}px glyphs: {''.join(map(chr, sorted(codes - mapped)))}"


if __name__ == "__main__":
    codes = inventory()
    if sys.argv[1:] != ["--check"]:
        OUT.mkdir(exist_ok=True)
        for size in (14, 20):
            generate(sys.argv[1], size, codes)
    check(codes)
    print(f"XC UI font coverage: {len(codes)} characters at 14 and 20 px")
